// frontend/src/pages/ReportPage.jsx
import React, { useEffect, useState } from 'react';
import { useParams, Link } from 'react-router-dom';
import { ArrowLeft, Printer, ShieldAlert, CheckCircle2 } from 'lucide-react';
import { useLanguage, DOC_TYPE_LABELS } from '../context/LanguageContext';
import BrandLogo from '../components/BrandLogo';

export default function ReportPage() {
  const { id } = useParams();
  const { t, formatNum } = useLanguage();
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch(`/api/lands/${id}`)
      .then((res) => res.json())
      .then((resData) => {
        if (resData.success) setData(resData.data);
      })
      .finally(() => setLoading(false));
  }, [id]);

  if (loading || !data) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-12">
        <div className="glass-card h-96 animate-pulse bg-amber-50/40" />
      </div>
    );
  }

  const { land, checklist, discrepancyAnalysis, disclaimer } = data;

  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 py-8 space-y-6">
      {/* Top Controls (Hidden when printing) */}
      <div className="flex items-center justify-between no-print">
        <Link
          to={`/land/${land.land_id}`}
          className="inline-flex items-center gap-2 text-sm font-bold text-stone-700 hover:text-amber-700"
        >
          <ArrowLeft className="w-4 h-4" />
          {t({ bn: 'ল্যান্ড প্রোফাইলে ফিরে যান', en: 'Back to Land Profile' })}
        </Link>

        <button
          type="button"
          onClick={() => window.print()}
          className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-stone-900 hover:bg-stone-800 text-white text-sm font-bold shadow-sm"
        >
          <Printer className="w-4 h-4 text-amber-400" />
          {t({ bn: 'রিপোর্ট প্রিন্ট / PDF সেভ করুন', en: 'Print / Save Report as PDF' })}
        </button>
      </div>

      {/* Printable Report Sheet */}
      <div className="bg-white border border-amber-300/80 rounded-2xl shadow-md p-6 sm:p-10 space-y-8">
        {/* Report Header */}
        <div className="flex flex-wrap items-center justify-between gap-4 border-b-2 border-amber-500/60 pb-5">
          <div className="flex items-center gap-3">
            <BrandLogo size="md" />
            <div>
              <h1 className="text-xl sm:text-2xl font-bold text-stone-900">
                {t({
                  bn: 'প্রাক-ক্রয় ভূমি ডিউ-ডিলিজেন্স সামারি রিপোর্ট',
                  en: 'Pre-Purchase Land Due-Diligence Summary Report'
                })}
              </h1>
              <p className="text-xs text-stone-600">
                {t({
                  bn: 'JomiSearch স্বয়ংক্রিয় নথি তুলনা ও যাচাই প্রতিবেদন',
                  en: 'Generated by JomiSearch Citizen Verification Assistant'
                })}
              </p>
            </div>
          </div>
          <div className="text-right text-xs text-stone-600">
            <p className="font-bold text-stone-900">
              {t({ bn: 'রিপোর্ট আইডি:', en: 'Report ID:' })} JS-REP-{formatNum(land.land_id)}
            </p>
            <p>{t({ bn: 'তারিখ:', en: 'Date:' })} {new Date().toISOString().slice(0, 10)}</p>
          </div>
        </div>

        {/* 1. Plot Summary */}
        <div className="space-y-3">
          <h2 className="text-base font-bold text-stone-900 uppercase tracking-wide border-b border-stone-200 pb-1">
            {t({ bn: '১. তফসিল ও জমির মৌলিক পরিচয়', en: '1. Plot Schedule & Identification' })}
          </h2>
          <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 text-xs sm:text-sm bg-amber-50/50 p-4 rounded-xl border border-amber-200">
            <p><strong>{t({ bn: 'বিভাগ ও জেলা:', en: 'Division & District:' })}</strong> {land.division}, {land.district}</p>
            <p><strong>{t({ bn: 'উপজেলা:', en: 'Upazila:' })}</strong> {land.upazila}</p>
            <p><strong>{t({ bn: 'মৌজা ও জেএল:', en: 'Mouza & JL:' })}</strong> {land.mouza} ({land.jl_number})</p>
            <p><strong>{t({ bn: 'খতিয়ান নম্বর:', en: 'Khatian No.:' })}</strong> {land.khatian_number}</p>
            <p><strong>{t({ bn: 'দাগ নম্বর:', en: 'Dag No.:' })}</strong> {formatNum(land.dag_number)}</p>
            <p><strong>{t({ bn: 'জমির পরিমাণ ও শ্রেণী:', en: 'Area & Class:' })}</strong> {t(land.formatted_area)} ({land.land_class})</p>
          </div>
        </div>

        {/* 2. Checklist Status Summary */}
        <div className="space-y-3">
          <h2 className="text-base font-bold text-stone-900 uppercase tracking-wide border-b border-stone-200 pb-1">
            {t({ bn: '২. চেকলিস্ট যাচাই সারাংশ', en: '2. Verification Checklist Summary' })}
          </h2>
          <div className="divide-y divide-stone-200 border border-stone-200 rounded-xl overflow-hidden text-xs sm:text-sm">
            {checklist.map((item) => (
              <div key={item.id} className="p-3.5 flex flex-col sm:flex-row sm:items-center justify-between gap-2 bg-white">
                <div>
                  <span className="font-bold text-stone-900 block">{t(item.category)}</span>
                  <span className="text-xs text-stone-600">{t(item.summary)}</span>
                </div>
                <span className="px-3 py-1 rounded-full text-xs font-bold bg-amber-100 text-amber-950 shrink-0 self-start sm:self-center">
                  {t(item.badge)}
                </span>
              </div>
            ))}
          </div>
        </div>

        {/* 3. Detected Discrepancies */}
        <div className="space-y-3">
          <h2 className="text-base font-bold text-stone-900 uppercase tracking-wide border-b border-stone-200 pb-1">
            {t({ bn: '৩. শনাক্তকৃত তথ্যগত অমিল ও ঝুঁকি বিশ্লেষণ', en: '3. Detected Discrepancies & Risk Findings' })}
          </h2>
          {discrepancyAnalysis.notices.length === 0 ? (
            <p className="text-xs sm:text-sm text-emerald-800 bg-emerald-50 p-3.5 rounded-xl border border-emerald-200 font-medium flex items-center gap-2">
              <CheckCircle2 className="w-4 h-4 shrink-0" />
              {t({
                bn: 'উপলব্ধ ডেমো দলিল ও খতিয়ানসমূহের মধ্যে কোনো দাগ বা পরিমাপগত অমিল পাওয়া যায়নি।',
                en: 'No plot number or normalized area discrepancies were found across the available records.'
              })}
            </p>
          ) : (
            <ul className="space-y-2 text-xs sm:text-sm">
              {discrepancyAnalysis.notices.map((n) => (
                <li key={n.id} className="p-3.5 rounded-xl bg-amber-50 border border-amber-300 text-stone-900">
                  <strong>• {t(n.field)}:</strong> {t(n.message)}
                </li>
              ))}
            </ul>
          )}
        </div>

        {/* 4. Buyer Next Steps */}
        <div className="space-y-3">
          <h2 className="text-base font-bold text-stone-900 uppercase tracking-wide border-b border-stone-200 pb-1">
            {t({ bn: '৪. ক্রেতার পরবর্তী করণীয় (Recommended Next Steps)', en: '4. Recommended Next Steps for Buyer' })}
          </h2>
          <ol className="list-decimal list-inside space-y-2 text-xs sm:text-sm text-stone-800 bg-stone-50 p-4 rounded-xl border border-stone-200">
            <li>
              {t({
                bn: 'সংশ্লিষ্ট উপজেলা ভূমি অফিস (AC Land) ও ইউনিয়ন তহশিল অফিসে মূল বালাম বহির সাথে খতিয়ান ও নামজারি মিলিয়ে দেখুন।',
                en: 'Verify Khatian and Mutation entries directly against Registry Balam books at the AC Land / Tahsil office.'
              })}
            </li>
            <li>
              {t({
                bn: 'সাব-রেজিস্ট্রি অফিস থেকে বিগত ২৫ বছরের নির্দায় সনদ (NEC - Non-Encumbrance Certificate) ও বায়া দলিলের ধারাবাহিকতা যাচাই করুন।',
                en: 'Obtain a 25-year Non-Encumbrance Certificate (NEC) and verify the chain of Baya Deeds at the Sub-Registry office.'
              })}
            </li>
            <li>
              {t({
                bn: 'সরেজমিনে আমিন বা সার্ভেয়ারের মাধ্যমে মৌজা ম্যাপ অনুযায়ী সীমানা ও বর্তমান দখলদারিত্ব পরিমাপ করুন।',
                en: 'Conduct a physical survey with a licensed surveyor against the Mouza map to confirm boundaries and actual possession.'
              })}
            </li>
            <li>
              {t({
                bn: 'ব্যাংক বন্ধক বা দেওয়ানি আদালতের নিষেধাজ্ঞা (Injunction) আছে কিনা তা একজন অভিজ্ঞ দেওয়ানি আইনজীবীর মাধ্যমে নিশ্চিত হোন।',
                en: 'Consult a property lawyer to check for undisclosed bank mortgages or pending civil court injunctions.'
              })}
            </li>
          </ol>
        </div>

        {/* Mandatory Official Guardrail Notice */}
        <div className="p-4 rounded-xl bg-amber-100/90 border border-amber-400 flex items-start gap-3 text-xs text-stone-900">
          <ShieldAlert className="w-5 h-5 text-amber-800 shrink-0 mt-0.5" />
          <p className="leading-relaxed font-medium">{t(disclaimer)}</p>
        </div>
      </div>
    </div>
  );
}